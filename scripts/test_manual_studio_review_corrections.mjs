import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile('apps/manual-studio/src/reviewCorrections.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {applyReviewCorrections}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const content='😀 first / second / last';
const finding=(quote,replacement)=>({category:'proofreading',severity:'problem',quote,replacement,start:content.indexOf(quote),end:content.indexOf(quote)+quote.length,message:'Test',suggestion:'Test',image:''});
const first=finding('first','expanded first'),second=finding('second',''),last=finding('last',null);
const issues=[first,second,last];
const all=applyReviewCorrections(content,issues,[second,first,last]);
assert.equal(all.content,'😀 expanded first /  / last');
assert.equal(all.applied,2);
assert.equal(all.issues.length,1);
assert.equal(all.content.slice(all.issues[0].start,all.issues[0].end),'last');
assert.equal(first.start,3,'original UTF-16 anchors are preserved');
const single=applyReviewCorrections(content,issues,[first]);
assert.equal(single.content.slice(single.issues[0].start,single.issues[0].end),'second');
assert.throws(()=>applyReviewCorrections(content,issues,[first,finding('first / second','combined')]),/重なる/);
assert.throws(()=>applyReviewCorrections('changed manuscript',issues,[first]),/変更/);
assert.throws(()=>applyReviewCorrections(content,issues,[{...first,start:-1}]),/変更/);
assert.deepEqual(applyReviewCorrections(content,issues,[last]).content,content);
console.log('Review corrections passed: atomic batch, Unicode anchors, deletion, reanchoring, overlap and stale rejection.');
