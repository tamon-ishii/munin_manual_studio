import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,mkdir,writeFile,readFile,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {chromium} from 'playwright-core';
const root=await mkdtemp(path.join(os.tmpdir(),'munin-performance-'));
const base='http://127.0.0.1:5185';
const counts=new Map();
let server,browser;
try {
  await mkdir(path.join(root,'docs/assets'),{recursive:true});
  await writeFile(path.join(root,'manual_setting.json'),JSON.stringify({docs:'docs',assets:'docs/assets',targets:['docs'],connection_type:'none'}));
  await writeFile(path.join(root,'docs/index.md'),'# Performance\n\nOriginal text\n');
  const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aCxoAAAAASUVORK5CYII=','base64');
  await writeFile(path.join(root,'docs/assets/a.png'),png);
  server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--config','apps/manual-studio/vite.config.ts','--port','5185','--strictPort'],{stdio:'ignore'});
  for(let i=0;i<100;i++){try{if((await fetch(base)).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:960}});
  page.setDefaultTimeout(30_000);console.log('performance: browser started');
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('manual-studio-editor-view','edit'));
  await page.route('**/__manual/rpc',async route=>{
    const request=route.request().postDataJSON();counts.set(request.action,(counts.get(request.action)||0)+1);
    const response=await route.fetch({headers:{...route.request().headers(),origin:'http://127.0.0.1:5174'}});
    await route.fulfill({response});
  });
  await page.goto(`${base}/?root=${encodeURIComponent(root)}&page=index.md`);
  await page.waitForFunction(()=>document.querySelector('#markdown-editor')?.value.includes('Original text'));
  await page.waitForFunction(()=>document.body.getAttribute('aria-busy')==='false');
  await page.getByRole('button',{name:'Markdownソース',exact:true}).click();
  const count=action=>counts.get(action)||0;
  const before={preview:count('editor-preview'),resources:count('resources-list')};
  const updated='# Performance\n\nChanged text\n';
  await page.locator('#markdown-editor').fill(updated);
  await page.waitForTimeout(1200);
  assert.equal(count('editor-save'),0,'editing does not save automatically');
  assert.equal(await readFile(path.join(root,'docs/index.md'),'utf8'),'# Performance\n\nOriginal text\n');
  await page.locator('#markdown-editor').press('ControlOrMeta+s');
  await page.waitForFunction(()=>document.querySelector('#save-state')?.textContent==='保存済み');
  assert.equal(await readFile(path.join(root,'docs/index.md'),'utf8'),updated);
  assert.equal(count('editor-preview'),before.preview,'hidden preview is not generated after editing');
  assert.equal(count('resources-list'),before.resources,'explicit save does not refresh the hidden library');
  await page.locator('#markdown-editor').press('ControlOrMeta+s');
  await page.waitForFunction(()=>document.body.getAttribute('aria-busy')==='false');
  assert.equal(count('resources-list'),before.resources,'manual save also skips the hidden library');
  await page.locator('[data-editor-view="split"]').click();
  await page.waitForFunction(()=>document.querySelector('#markdown-preview')?.contentDocument?.body?.textContent.includes('Changed text'));
  assert.equal(count('editor-preview'),before.preview+1,'revealing preview generates the latest document once');
  await page.locator('[data-tab="screenshots"]').click();
  await page.waitForFunction(()=>[...document.querySelectorAll('#screenshot-library-list img')].some(img=>img.complete&&img.naturalWidth>0));
  assert.equal(count('screenshots-list'),0,'combined resource response avoids duplicate screenshot listing');
  const thumbnails=count('resources-thumbnail');assert.ok(thumbnails>0);
  await page.locator('#resource-management-menu > summary').click();
  await page.locator('#screenshot-library-refresh').click();
  await page.waitForFunction(()=>document.body.getAttribute('aria-busy')==='false');
  await page.waitForFunction(()=>[...document.querySelectorAll('#screenshot-library-list img')].some(img=>img.complete&&img.naturalWidth>0));
  assert.equal(count('resources-thumbnail'),thumbnails,'unchanged thumbnail survives list refresh');
  // Even a same-path, same-size external write invalidates the metadata revision.
  await writeFile(path.join(root,'docs/assets/a.png'),png);
  await page.locator('#resource-management-menu > summary').click();
  await page.locator('#screenshot-library-refresh').click();
  await page.waitForFunction(()=>document.body.getAttribute('aria-busy')==='false');
  await page.waitForFunction(()=>[...document.querySelectorAll('#screenshot-library-list img')].some(img=>img.complete&&img.naturalWidth>0));
  assert.equal(count('resources-thumbnail'),thumbnails+1,'same-path external write invalidates the thumbnail revision');
  console.log('performance: cache checks passed');
  await page.locator('[data-tab="editor"]').click();
  assert.equal(await page.locator('#save-state').isVisible(),false);
  assert.equal(await page.locator('#panel-editor .column-label').count(),0);
  assert.equal(await page.locator('.workspace-ai-group #reader-review').count(),1);
  assert.equal(await page.locator('.workspace-ai-group #editor-screenshot-ai').count(),1);
  assert.equal(await page.locator('#document-tabs #editor-screenshot-ai').count(),0);
  await mkdir(path.join(root,'docs/moved'),{recursive:true});
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#markdown-editor')?.value.includes('Changed text'));
  await page.getByRole('tab',{name:'ファイルツリー',exact:true}).click();
  await page.locator('#tree-search').fill('index.md');
  await page.locator('[data-page$="index.md"]').first().click({button:'right'});
  await page.getByRole('menuitem',{name:'移動してリンクを更新',exact:true}).click();
  await page.getByRole('textbox',{name:'移動先（プロジェクト相対パス）',exact:true}).fill('docs/moved/index.md');
  console.log('performance: move dialog opened');
  await page.getByRole('button',{name:'リンク更新を確認',exact:true}).click();
  await page.locator('#file-move-dialog').getByRole('button',{name:'移動してリンクを更新',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('リンクを更新しました'));
  assert.equal(await readFile(path.join(root,'docs/moved/index.md'),'utf8'),updated);
  await page.getByRole('button',{name:'Markdownソース',exact:true}).click();
  console.log('performance: move applied');
  const gfm='# GFM\n\n> [!NOTE]\n> Alert content\n\n~~deleted~~\n\n- [x] done\n\n| A | B |\n| - | - |\n| x | y |\n\nhttps://example.com\n';
  await page.locator('#markdown-editor').fill(gfm);
  await page.getByRole('button',{name:'Milkdown編集',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-gfm-alert="NOTE"]'));
  await page.getByRole('button',{name:'Markdownソース',exact:true}).click();
  assert.match(await page.locator('#markdown-editor').inputValue(),/> \[!NOTE\]/);
  await page.getByRole('combobox',{name:'GitHubアラートを挿入',exact:true}).selectOption('WARNING');
  assert.match(await page.locator('#markdown-editor').inputValue(),/> \[!WARNING\]/);
  const control=await browser.newPage();
  await control.addInitScript(()=>{window.cancelCommands=[];window.__TAURI_INTERNALS__={invoke:async command=>{window.cancelCommands.push(command);}};});
  await control.goto(`${base}/recording-control.html`);
  await control.locator('#capture-cancel').waitFor();
  await control.keyboard.press('Escape');
  await control.waitForFunction(()=>window.cancelCommands.includes('cancel_operation_recording'));
  await control.close();
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({result:'passed',checks:['no hidden preview work','no library refresh on save','one latest preview','one bundled resource request','thumbnail reuse and external-write invalidation'],requests:Object.fromEntries(counts)},null,2));
} finally {
  await browser?.close();server?.kill();await rm(root,{recursive:true,force:true});
}
